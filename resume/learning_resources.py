def get_learning_resources(user_skills):
    """Return curated learning resources for user's skills."""
    resources = {}
    for skill in user_skills:
        skill_lower = skill.lower()
        
        # Direct match
        if skill_lower in LEARNING_RESOURCES:
            resources[skill] = LEARNING_RESOURCES[skill_lower]
        else:
            # Partial match
            for key in LEARNING_RESOURCES:
                if key in skill_lower or skill_lower in key:
                    resources[skill] = LEARNING_RESOURCES[key]
                    break
                # Check for multi-word skill matches
                key_words = set(key.split())
                skill_words = set(skill_lower.split())
                if len(key_words & skill_words) >= min(1, len(key_words)):
                    resources[skill] = LEARNING_RESOURCES[key]
                    break
    
    return resources
